#!/usr/bin/env node
// Reads the web app's SVG sprite (apps/web/src/components/Icons.tsx) and writes its symbols as plain
// SVG strings (src/platform/icons.gen.ts): the mini program has no inline SVG, so icons become
// background images built from these. Run after changing the sprite: node scripts/gen-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const src = readFileSync(here('../../web/src/components/Icons.tsx'), 'utf8');
const attr = (s) =>
  s
    .replace(
      /\b(fillRule|clipRule|strokeWidth|strokeLinecap|strokeLinejoin)=/g,
      (m, a) => `${a.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}=`,
    )
    .replace(/\s+/g, ' ')
    .replace(/> </g, '><')
    .trim();
const out = {};
for (const m of src.matchAll(/<symbol id="([^"]+)" viewBox="([^"]+)">([\s\S]*?)<\/symbol>/g)) {
  out[m[1]] = { viewBox: m[2], body: attr(m[3]) };
}
if (Object.keys(out).length < 10) throw new Error('sprite not found or changed shape');
writeFileSync(
  here('../src/platform/icons.gen.ts'),
  `// Generated by scripts/gen-icons.mjs from apps/web/src/components/Icons.tsx — do not edit.\n` +
    `export const SYMBOLS: Record<string, { viewBox: string; body: string }> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(`icons: ${Object.keys(out).length} symbols`);
